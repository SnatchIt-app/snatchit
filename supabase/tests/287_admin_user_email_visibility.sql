BEGIN;
SELECT plan(15);
SELECT tap.seed_core();
SELECT ok(not has_function_privilege('anon','ops.admin_user_emails(uuid[])','EXECUTE'),'anon cannot reach full-email reader');
SELECT ok(not has_function_privilege('service_role','ops.admin_user_emails(uuid[])','EXECUTE'),'service role has no caller bypass');
SELECT tap.login(tap.admin_user());
SELECT throws_ok($$select ops.admin_user_emails(array[tap.buyer()])$$,'P0001','step_up_unavailable: the session carries no aal claim','admin must provide MFA claim');
SELECT set_config('request.jwt.claims',(current_setting('request.jwt.claims')::jsonb||'{"aal":"aal2"}'::jsonb)::text,true);
SELECT is(ops.admin_user_emails(array[tap.buyer()])->0->>'email','buyer@test.local','admin receives the exact full email');
SELECT is(ops.admin_user_emails(array[tap.buyer()])->0->>'id',tap.buyer()::text,'full email is bound to requested identity');
SELECT is(jsonb_array_length(ops.admin_user_emails(array[tap.buyer(),tap.buyer()])),1,'duplicates do not repeat contacts');
SELECT is(ops.admin_user_emails(NULL::uuid[]),'[]'::jsonb,'missing IDs never return all users');
SELECT is(ops.admin_user_emails(array[gen_random_uuid()]),'[]'::jsonb,'unknown ID never broadens the lookup');
SELECT throws_ok($$select ops.admin_user_emails(array_fill(tap.buyer(),array[201]))$$,'P0001','invalid_input: at most 200 user ids','bounded lookup refuses oversized input');
SELECT throws_ok($$select ops.admin_user_emails(array[NULL::uuid])$$,'P0001','invalid_input: null user id','malformed input refuses');
SELECT ok(not(ops.admin_user_emails(array[tap.buyer()])->0 ? 'phone'),'no full phone or authentication object is returned');
SELECT tap.logout();
INSERT INTO kernel.platform_role(identity_id,role,granted_by) VALUES(tap.other_user(),'platform_support',tap.admin_user());
SELECT tap.login(tap.other_user());
SELECT set_config('request.jwt.claims',(current_setting('request.jwt.claims')::jsonb||'{"aal":"aal2"}'::jsonb)::text,true);
SELECT throws_ok($$select ops.admin_user_emails(array[tap.buyer()])$$,'42501','insufficient_privilege: requires one of {platform_admin} (you are platform_support)','support operator cannot read full emails');
SELECT tap.logout();
CREATE TEMP TABLE contact_guard AS SELECT pg_get_functiondef('ops.admin_user_emails(uuid[])'::regprocedure) source;
DO $weaken$ begin execute replace((select source from contact_guard),$needle$perform ops.assert_role(array['platform_admin']);$needle$,'perform ops.assert_reader();');end $weaken$;
SELECT tap.login(tap.other_user());
SELECT set_config('request.jwt.claims',(current_setting('request.jwt.claims')::jsonb||'{"aal":"aal2"}'::jsonb)::text,true);
SELECT is(ops.admin_user_emails(array[tap.buyer()])->0->>'email','buyer@test.local','negative control demonstrates the support leak if admin gate is removed');
SELECT tap.logout();
DO $restore$ begin execute (select source from contact_guard);end $restore$;
SELECT tap.login(tap.buyer());
SELECT set_config('request.jwt.claims',(current_setting('request.jwt.claims')::jsonb||'{"aal":"aal2"}'::jsonb)::text,true);
SELECT throws_ok($$select ops.admin_user_emails(array[tap.buyer()])$$,'42501','insufficient_privilege: operator role required','ordinary buyer cannot read even their contact through admin endpoint');
SELECT tap.logout();
SELECT ok(not has_table_privilege('authenticated','auth.users','SELECT'),'no auth-table grant introduced');
SELECT * FROM finish();
ROLLBACK;
